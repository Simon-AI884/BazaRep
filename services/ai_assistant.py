import os
import openai

from services.catalog_search import (
    find_relevant_pumps,
    format_pumps_for_ai,
    format_scenario_for_ai
)


SYSTEM_PROMPT = """
Ти — інтелектуальний консультант інтернет-магазину TechBaza в Україні.
Твоя спеціалізація — підбір насосного обладнання.

Відповідай тільки українською мовою.
Пиши просто, зрозуміло, професійно і без зайвої води.

Головний принцип:
не існує одного універсального насоса для задачі. Підбір залежить від джерела води, глибини, типу встановлення, якості води, потрібної подачі, напору, відстані, автоматики, бюджету і умов експлуатації.

Якщо для задачі можливі різні типи насосів, наприклад для колодязя можуть підходити поверхневий насос, насосна станція або занурювальний насос, не роби остаточний вибір без уточнення бажаного типу встановлення.

Працюй за логікою:
1. Спочатку визнач задачу клієнта.
2. Поясни, які категорії насосів можуть підходити.
3. Якщо клієнт явно вказав тип насоса, підбирай тільки серед цього типу.
4. Якщо клієнт не вказав тип насоса, а можливі різні варіанти, поясни різницю і постав уточнювальне питання.
5. Якщо в каталозі знайдені товари, покажи їх як попередні варіанти.
6. Не вигадуй ціну, наявність, характеристики або гарантію.
7. Якщо насос не підходить за умовами, чесно попередь.
8. Якщо є посилання на товар, додай його в кінці.

Не кажи клієнту “вам точно потрібен цей насос”, якщо даних недостатньо.
Краще кажи: “попередньо можна розглянути”, “для точного підбору потрібно уточнити”.
"""


def get_model_name() -> str:
    return os.getenv(
        "OPENAI_MODEL",
        "ft:gpt-4.1-nano-2025-04-14:techbaza:techbaza:DG9m3myJ"
    )


def is_greeting_or_smalltalk(user_message: str) -> bool:
    text = user_message.lower().strip()

    greetings = [
        "привіт", "привет", "добрий день", "добрый день",
        "доброго дня", "здравствуйте", "вітаю", "hello", "hi"
    ]

    thanks = [
        "дякую", "спасибо", "дякую вам", "спасибо вам"
    ]

    if text in greetings or text in thanks:
        return True

    if len(text) <= 20 and any(word in text for word in greetings):
        return True

    return False


def is_pump_related_request(user_message: str) -> bool:
    text = user_message.lower()

    pump_keywords = [
        "насос", "помпа", "мотопомпа", "станція", "станция",
        "колод", "свердлов", "скваж", "полив", "зрош", "орош",
        "вода", "води", "водоснаб", "водопостач",
        "дренаж", "підвал", "подвал", "каналіз", "канализ",
        "фекал", "басейн", "бассейн", "опалення", "отоплен",
        "тиск", "давление", "напір", "напор",
        "ємність", "емкость", "резервуар", "цистерн",
        "сад", "город", "теплиц", "парник",
        "брудна", "грязная", "чиста", "чистая"
    ]

    return any(keyword in text for keyword in pump_keywords)


async def get_ai_response(user_message: str) -> str:
    if is_greeting_or_smalltalk(user_message):
        return (
            "Вітаю! Я допоможу підібрати насос або насосне обладнання для TechBaza.\n\n"
            "Напишіть, будь ласка, для чого потрібен насос: колодязь, свердловина, полив, будинок, "
            "дренаж, каналізація, басейн, опалення чи підвищення тиску.\n\n"
            "Ще краще, якщо одразу вкажете: джерело води, глибину, відстань, якість води та бажаний тип насоса "
            "— поверхневий, занурювальний або насосна станція."
        )

    if not is_pump_related_request(user_message):
        return (
            "Я можу допомогти саме з підбором насосів і насосного обладнання TechBaza.\n\n"
            "Опишіть, будь ласка, вашу задачу: звідки потрібно брати воду, яка глибина, "
            "для чого насос — будинок, полив, свердловина, колодязь, дренаж, каналізація, басейн чи інша задача."
        )

    client = openai.AsyncOpenAI(api_key=os.getenv("OPENAI_API_KEY"))

    search_result = find_relevant_pumps(user_message, limit=8)

    scenario = search_result["scenario"]
    relevant_pumps = search_result["pumps"]

    scenario_context = format_scenario_for_ai(scenario)
    catalog_context = format_pumps_for_ai(relevant_pumps)

    response = await client.chat.completions.create(
        model=get_model_name(),
        messages=[
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": f"""
Запит клієнта:
{user_message}

{scenario_context}

Знайдені товари з каталогу TechBaza:
{catalog_context}

Дай відповідь клієнту українською мовою.

Правила відповіді:
- Спочатку коротко поясни, які типи насосів можуть підходити під задачу.
- Якщо потрібно уточнити тип встановлення, обов'язково запитай: поверхневий, занурювальний чи насосна станція.
- Якщо клієнт уже вказав тип насоса, не пропонуй інші типи як основні.
- Якщо знайдено товари з каталогу, покажи 1-3 попередні варіанти.
- Обери попередньо найкращий варіант тільки тоді, коли це не суперечить умовам клієнта.
- Якщо даних недостатньо для точного підбору, напиши, які параметри потрібно уточнити.
- Не вигадуй ціну, наявність і характеристики.
- Якщо посилання на товар є, додай його в кінці.
"""
            },
        ],
        max_tokens=900,
    )

    return response.choices[0].message.content